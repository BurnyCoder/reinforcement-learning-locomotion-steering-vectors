"""Independently check every published Ant metric, interval and saved trajectory shard.

The reference consumes original episodes, not production estimators or earlier audit
calculations. Six-decimal plotted coordinates are display rounding, not raw precision.
"""
import numpy as np
from scipy import stats

from .audit import condition, differences, read_json
from .numerical import METRICS, episode_summary


def trace(item):
    """Reconstruct a displayed trajectory and reward blocks from the actual saved transitions."""
    n=int(item['length']);dt=float(item['dt'])
    indices=sorted(set(range(0,n+1,10))|{n}|({100} if n>100 else set()))
    scalar=episode_summary(item,100)
    summary={METRICS.get(k,k):v for k,v in scalar.items()}
    summary['total_return']=float(item['reward'].sum())
    result=dict(length=n,failed=bool(scalar['failure']),prefix_only=bool(scalar['prefix_only']),steps=indices,
                time=[round(k*dt,6) for k in indices],summary=summary,
                reward=[None]+[round(float(item['reward'][a:b].mean()),6) for a,b in zip(indices[:-1],indices[1:])])
    for key,label in [('x_velocity','x'),('y_velocity','y')]:
        result[label]=[round(float(x),6) for x in (np.r_[0.,np.cumsum(item[key])*dt])[indices]]
    return result


def publication(root, destination=None):
    """Check the current generated bytes; the builder must fail rather than publish stale numbers."""
    destination = root if destination is None else destination
    evidence=read_json(destination/'reports/ant-publication/evidence.json')
    mismatches=[];counts={}
    if (destination/'site/data/ant005.json').read_bytes() != (destination/'reports/ant-publication/evidence.json').read_bytes():
        raise ValueError('Explorer and publication evidence differ')
    for cohort in evidence['cohorts']:
        name=cohort['id']
        directory=root/('runs/ant-005-independent-audit/episodes/audit' if name=='fresh_audit' else 'runs/ant-classic-005/episodes/'+name)
        base=condition(directory/'baseline');before=[episode_summary(x,100) for x in base]
        base_trace={int(x['seed']):trace(x) for x in base};effects={};count=0
        for row in cohort['conditions']:
            items=base if row['id']=='baseline' else condition(directory/row['id'])
            if [int(x['seed']) for x in items] != [int(x['seed']) for x in base]:
                raise ValueError('Unpaired published condition')
            after=[episode_summary(x,100) for x in items]
            means={METRICS[k]:float(np.mean([s[k] for s in after])) for k in METRICS}
            means.update(total_return=float(np.mean([x['reward'].sum() for x in items])),failures=int(sum(x['failure'] for x in after)),
                         prefix_only=int(sum(x['prefix_only'] for x in after)),forward_speed_retention=float(np.mean([x['speed'] for x in after])/np.mean([x['speed'] for x in before])))
            mismatches+=differences(means,row['metrics'],name+'/'+row['id']+'/metrics',require_fields=True)
            delta=np.array([b['lateral']-a['lateral'] for a,b in zip(before,after)]);effects[row['id']]=float(delta.mean())
            if row['id']!='baseline':
                method=row['pairedEffect']['ci_method']
                if method.startswith('saved paired BCa'):
                    ci=stats.bootstrap((delta,),np.mean,method='BCa',n_resamples=10000,random_state=20261016).confidence_interval
                    interval=[float(ci.low),float(ci.high)]
                else:
                    seed=(710 if name=='validation' else 720) if method.startswith('saved paired percentile') else 20261029
                    draws=np.random.default_rng(seed).integers(len(delta),size=(2000,len(delta)))
                    interval=np.quantile(delta[draws].mean(1),[.025,.975]).tolist()
                mismatches+=differences(dict(mean=float(delta.mean()),ci95=interval),row['pairedEffect'],name+'/'+row['id']+'/interval',require_fields=True)
            windows=[]
            for start in range(0,max(int(x['length']) for x in items),100):
                values=[float(x['reward'][start:start+100].mean()) for x in items if int(x['length'])>start]
                windows.append(dict(start=start,end=start+100,n=len(values),mean=float(np.mean(values))))
            mismatches+=differences(windows,row['reward_windows'],name+'/'+row['id']+'/rewards',require_fields=True)
            shard=read_json(destination/'site'/row['episodesUrl'])
            expected=[dict(seed=int(x['seed']),baseline=base_trace[int(x['seed'])],treated=trace(x)) for x in items]
            mismatches+=differences(expected,shard['episodes'],name+'/'+row['id']+'/trajectories',require_fields=True)
            count+=len(items)
        for row in cohort['conditions']:
            others=[x for x in cohort['conditions'] if x['vector']==row['vector'] and x['alpha']==-row['alpha'] and row['alpha']!=0]
            if row['oddEven'] and others:
                a,b=(effects[row['id']],effects[others[0]['id']]) if row['alpha']<0 else (effects[others[0]['id']],effects[row['id']])
                mismatches+=differences(dict(odd=(b-a)/2,even=(b+a)/2),row['oddEven'],name+'/'+row['id']+'/odd_even',require_fields=True)
        counts[name]=dict(conditions=len(cohort['conditions']),trajectory_pairs=count)
    return dict(cohorts=counts,differences=mismatches,display_precision='Coordinates and reward blocks are rounded to six decimals; raw effects retain full precision.')
