"""Regenerate the Ant publication from verified saved evidence, without any new rollouts.

Usage: uv run --no-sync python scripts/build_ant_publication.py [--check]
Missing evidence is restored from the immutable Hub manifest during a normal build.
--check validates existing inputs and compares temporary outputs without editing publications.
"""

from __future__ import annotations

import argparse
import hashlib
import logging
import tempfile
import time
from datetime import datetime, timezone
from pathlib import Path

from rl_locomotion_steering_vectors.publication.evidence import build_evidence
from rl_locomotion_steering_vectors.publication.figures import build_figures
from rl_locomotion_steering_vectors.publication.inputs import canonical_json, validate_inputs, write_json


def generate(root: Path, verified: dict, output_root: Path) -> list[Path]:
    """Keep orchestration thin: evidence, figures, documents and matching public JSON."""
    from reportlab import rl_config
    from rl_locomotion_steering_vectors.publication.documents import render_documents

    rl_config.invariant = 1  # ReportLab fixes PDF timestamps/IDs for byte-stable regeneration.
    evidence, outputs = build_evidence(root, verified, output_root=output_root)
    outputs.extend(build_figures(evidence, output_root))
    evidence["provenance"].pop("derived_evidence_sha256", None)
    evidence["provenance"]["derived_evidence_sha256"] = hashlib.sha256(canonical_json(evidence)).hexdigest()
    outputs.extend(render_documents(root, evidence, output_root=output_root))
    for relative in ("reports/ant-publication/evidence.json", "site/data/ant005.json"):
        outputs.append(write_json(output_root / relative, evidence))
    return outputs


def compare_outputs(root: Path, stage: Path, generated: list[Path]) -> list[str]:
    """Compare every generated byte and reject leftover episode shards from an older build."""
    relative_paths = {path.relative_to(stage) for path in generated}
    stale = [path.as_posix() for path in sorted(relative_paths) if not (root / path).is_file() or (root / path).read_bytes() != (stage / path).read_bytes()]
    existing = {path.relative_to(root) for path in (root / "site/data/episodes").glob("*.json")}
    stale.extend(f"obsolete generated shard: {path.as_posix()}" for path in sorted(existing - relative_paths))
    return stale


def main() -> int:
    """Verify inputs before rendering and never reinterpret a failed scientific result."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail on stale output; do not edit publications or restore inputs")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    handlers = [logging.StreamHandler()]
    if not args.check:
        log_dir = root / "tmp/ant-publication"
        log_dir.mkdir(parents=True, exist_ok=True)
        log_path = log_dir / (datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S%fZ") + ".log")
        handlers.append(logging.FileHandler(log_path, encoding="utf-8"))
    logging.basicConfig(level=logging.INFO, format="%(asctime)sZ %(levelname)s %(message)s", handlers=handlers, force=True)
    logging.Formatter.converter = time.gmtime
    verified = validate_inputs(root, root / "reports/ant-publication/inputs.json", restore=not args.check)
    if args.check:
        temporary_parent = root / "tmp/ant-publication"
        temporary_parent.mkdir(parents=True, exist_ok=True)
        with tempfile.TemporaryDirectory(prefix="check-", dir=temporary_parent) as temporary:
            stage = Path(temporary)
            generated = generate(root, verified, stage)
            stale = compare_outputs(root, stage, generated)
        if stale:
            for relative in stale:
                logging.error("Stale publication output: %s", relative)
            return 1
        logging.info("All %d publication outputs match their saved-data regeneration", len(generated))
    else:
        generated = generate(root, verified, root)
        logging.info("Regenerated %d publication outputs from %d verified saved inputs; no simulation", len(generated), verified["files_verified"])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
